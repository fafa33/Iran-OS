# توپولوژی سامانه — IranOS

## هدف

این سند نقشه کلان معماری IranOS را تعریف می‌کند.

توپولوژی سامانه نشان می‌دهد که لایه‌های اصلی چگونه به هم متصل می‌شوند، داده‌ها از چه مسیری حرکت می‌کنند، عامل‌ها کجا قرار می‌گیرند، هسته چگونه کنترل اعمال می‌کند و دفترکل ملی چگونه ثبت و حسابرسی را انجام می‌دهد.

---

# نمای کلان سامانه

IranOS از چند لایه اصلی تشکیل می‌شود:

1. لایه منشور
2. لایه هسته
3. لایه عامل‌های هوشمند
4. لایه گردش‌کارها
5. لایه اوراکل‌ها
6. لایه قراردادهای هوشمند
7. لایه دفترکل ملی
8. لایه نظارت انسانی
9. لایه امنیت و ماشه اضطراری

